"""Generate src/text/unicode_tables.h: the Unicode data the tokenizer needs, from Python's unicodedata.

    python3 tools/gen_unicode_tables.py > src/text/unicode_tables.h

- general categories, as ranges (for the regex classes \\p{L}, \\p{N}, ... in pre-tokenizer patterns)
- canonical decompositions, combining classes and primary compositions (for NFC / NFD normalizers)

The tables follow the Unicode version of the Python that runs this (printed in the header). Hangul
syllables are composed and decomposed algorithmically in src/text/unicode.cpp, so they are left out here.
"""
import sys
import unicodedata

CATEGORIES = ["Cn", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi",
              "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co"]
MAX = 0x110000
HANGUL = range(0xAC00, 0xAC00 + 11172)


def ranges(value_of):
    """Maximal runs of equal value, as (first, last, value); runs with value 0 left out."""
    out, start, cur = [], 0, value_of(0)
    for cp in range(1, MAX + 1):
        v = value_of(cp) if cp < MAX else None
        if v != cur:
            if cur:
                out.append((start, cp - 1, cur))
            start, cur = cp, v
    return out


def main():
    cat = {c: i for i, c in enumerate(CATEGORIES)}
    categories = ranges(lambda cp: cat[unicodedata.category(chr(cp))])
    combining = ranges(lambda cp: unicodedata.combining(chr(cp)))
    decomp, comp = [], []
    for cp in range(MAX):
        if cp in HANGUL:
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        assert len(parts) <= 2, hex(cp)
        decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
        # a primary composite: two-part, starter first, and NFC keeps it (no composition exclusion)
        if len(parts) == 2 and unicodedata.combining(chr(parts[0])) == 0 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            comp.append((parts[0], parts[1], cp))
    comp.sort()
    w = sys.stdout.write
    w(f"// Generated by tools/gen_unicode_tables.py from Unicode {unicodedata.unidata_version} (Python's unicodedata). Do not edit.\n")
    w("#pragma once\n\n#include <cstdint>\n\nnamespace tfi::detail::unicode_data {\n\n")
    w(f"constexpr const char* kVersion = \"{unicodedata.unidata_version}\";\n\n")
    w("// General categories, in the order of the values in kCategories (0 = Cn, unassigned).\n")
    w("constexpr const char* kCategoryNames[] = {" + ", ".join(f'"{c}"' for c in CATEGORIES) + "};\n")
    w("struct Range { uint32_t first, last; uint8_t value; };\n")
    for name, table in (("kCategories", categories), ("kCombiningClasses", combining)):
        w(f"constexpr Range {name}[] = {{\n")
        for i in range(0, len(table), 4):
            w("    " + " ".join(f"{{0x{a:X}, 0x{b:X}, {v}}}," for a, b, v in table[i:i + 4]) + "\n")
        w("};\n")
    w("// Canonical decompositions (one level; second = 0 for a single code point), sorted by code point.\n")
    w("struct Decomposition { uint32_t cp, first, second; };\nconstexpr Decomposition kDecompositions[] = {\n")
    for i in range(0, len(decomp), 4):
        w("    " + " ".join(f"{{0x{a:X}, 0x{b:X}, 0x{c:X}}}," for a, b, c in decomp[i:i + 4]) + "\n")
    w("};\n// Primary compositions: first + second -> cp, sorted by (first, second).\n")
    w("struct Composition { uint32_t first, second, cp; };\nconstexpr Composition kCompositions[] = {\n")
    for i in range(0, len(comp), 4):
        w("    " + " ".join(f"{{0x{a:X}, 0x{b:X}, 0x{c:X}}}," for a, b, c in comp[i:i + 4]) + "\n")
    w("};\n\n}  // namespace tfi::detail::unicode_data\n")


if __name__ == "__main__":
    main()
